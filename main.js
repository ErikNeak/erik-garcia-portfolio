    function initHeroMedia() {
      const videoPlayer = document.getElementById('heroVideoPlayer');
      const videoNotice = document.getElementById('heroVideoNotice');
      const videoInput = document.getElementById('heroVideoInput');
      const btnPlayToggle = document.getElementById('btnVideoPlayToggle');
      const btnMuteToggle = document.getElementById('btnVideoMuteToggle');
      const videoPlayText = document.getElementById('videoPlayText');
      const videoMuteText = document.getElementById('videoMuteText');
      const stage = document.getElementById('heroParallaxStage');
      const card = document.getElementById('heroParallaxCard');
      const aura = document.getElementById('heroAura');
      const clockEl = document.getElementById('heroClock');

      // 1. Reloj digital en tiempo real NERV CDMX
      if (clockEl) {
        function updateClock() {
          const now = new Date();
          clockEl.textContent = now.toLocaleTimeString('es-MX', { hour12: false });
        }
        updateClock();
        setInterval(updateClock, 1000);
      }

      // 1.1 Telemetría dinámica de FPS estilo motor de videojuegos (fluctuación 58.2 - 61.4 FPS)
      const fpsEl = document.getElementById('heroFpsCounter');
      if (fpsEl) {
        function jitterHeroFps() {
          const baseFps = 60.0;
          const jitter = (Math.random() * 2.8) - 1.3; // Rango típico entre 58.7 y 61.5
          const currentFps = (baseFps + jitter).toFixed(1);
          fpsEl.textContent = `${currentFps} FPS`;
          if (parseFloat(currentFps) < 58.8) {
            fpsEl.className = 'text-eva-amber font-mono font-bold tracking-wider transition-colors';
          } else {
            fpsEl.className = 'text-eva-acid font-mono font-bold tracking-wider transition-colors';
          }
        }
        jitterHeroFps();
        setInterval(jitterHeroFps, 320);
      }

      // 2. Efecto de inclinación 3D e interactividad Parallax con cursor
      if (stage && card) {
        let isHovered = false;
        stage.addEventListener('mouseenter', () => { isHovered = true; });
        stage.addEventListener('mousemove', (e) => {
          if (!isHovered) return;
          const rect = stage.getBoundingClientRect();
          const x = e.clientX - rect.left;
          const y = e.clientY - rect.top;
          const centerX = rect.width / 2;
          const centerY = rect.height / 2;
          const rotateX = ((y - centerY) / centerY) * -10;
          const rotateY = ((x - centerX) / centerX) * 12;

          card.style.transform = `perspective(1000px) rotateX(${rotateX.toFixed(2)}deg) rotateY(${rotateY.toFixed(2)}deg) scale3d(1.02, 1.02, 1.02)`;
          if (aura) {
            aura.style.transform = `translate3d(${((x - centerX) * 0.06).toFixed(1)}px, ${((y - centerY) * 0.06).toFixed(1)}px, 0)`;
          }
        });

        stage.addEventListener('mouseleave', () => {
          isHovered = false;
          card.style.transform = 'perspective(1000px) rotateX(0deg) rotateY(0deg) scale3d(1, 1, 1)';
          if (aura) {
            aura.style.transform = 'translate3d(0, 0, 0)';
          }
        });
      }

      // 3. Controles interactivos de video y archivo local
      if (videoPlayer && typeof videoPlayer.play === 'function') {
        try {
          const playPromise = videoPlayer.play();
          if (playPromise !== undefined) {
            playPromise.then(() => {
              if (videoNotice) videoNotice.classList.add('hidden');
            }).catch(() => {
              if (videoNotice && (!videoPlayer.src || (typeof HTMLMediaElement !== 'undefined' && videoPlayer.networkState === HTMLMediaElement.NETWORK_NO_SOURCE))) {
                videoNotice.classList.remove('hidden');
              }
            });
          }
        } catch (err) {
          // Autoplay prevenido silenciosamente
        }

        videoPlayer.addEventListener('error', () => {
          if (videoNotice) videoNotice.classList.remove('hidden');
        });

        if (btnPlayToggle) {
          btnPlayToggle.addEventListener('click', () => {
            if (videoPlayer.paused) {
              videoPlayer.play();
              if (videoPlayText) videoPlayText.textContent = "PAUSA";
              btnPlayToggle.innerHTML = '<i data-lucide="pause" class="w-3.5 h-3.5 text-eva-acid"></i><span id="videoPlayText">PAUSA</span>';
            } else {
              videoPlayer.pause();
              if (videoPlayText) videoPlayText.textContent = "REPRODUCIR";
              btnPlayToggle.innerHTML = '<i data-lucide="play" class="w-3.5 h-3.5 text-eva-acid"></i><span id="videoPlayText">REPRODUCIR</span>';
            }
            refreshLucideIcons();
          });
        }

        if (btnMuteToggle) {
          btnMuteToggle.addEventListener('click', () => {
            videoPlayer.muted = !videoPlayer.muted;
            btnMuteToggle.innerHTML = videoPlayer.muted
              ? '<i data-lucide="volume-x" class="w-3.5 h-3.5 text-eva-mist"></i>'
              : '<i data-lucide="volume-2" class="w-3.5 h-3.5 text-eva-acid"></i>';
            refreshLucideIcons();
          });
        }

        if (videoInput) {
          videoInput.addEventListener('change', (e) => {
            const file = e.target.files && e.target.files[0];
            if (file) {
              const fileUrl = URL.createObjectURL(file);
              videoPlayer.src = fileUrl;
              if (videoNotice) videoNotice.classList.add('hidden');
              videoPlayer.play();
              if (videoPlayText) videoPlayText.textContent = "PAUSA";
              refreshLucideIcons();
            }
          });
        }
      }
    }

