    function initBootSequence() {
      const bootScreen = document.getElementById("boot-screen");
      // Si estamos en archivo.html (sin boot-screen) o venimos de navegación interna con hash (#hero, #trayectoria, etc.)
      if (!bootScreen) {
        document.body.style.overflow = "auto";
        observeElements();
        animateKPIs();
        return;
      }

      if (window.location.hash && window.location.hash.length > 1) {
        hasLaunched = true;
        bootScreen.style.display = "none";
        bootScreen.style.pointerEvents = "none";
        document.body.style.overflow = "auto";
        observeElements();
        animateKPIs();
        return;
      }

      document.body.style.overflow = "hidden";
      const syncRateEl = document.getElementById("boot-sync-rate");
      const progressBar = document.getElementById("boot-progress-bar");
      const logContainer = document.getElementById("boot-log-container");
      const launchBtn = document.getElementById("btn-launch");
      const skipBtn = document.getElementById("btn-skip-boot");
      const syncBlocks = document.querySelectorAll(".sync-stage-block");

      if (skipBtn) {
        skipBtn.onclick = () => launchPortfolio(true);
      }

      // Habilitar botón para clic inmediato en cualquier segundo
      if (launchBtn) {
        launchBtn.disabled = false;
        launchBtn.innerText = "⚡ ENTRAR AL PORTAFOLIO";
        launchBtn.classList.add("cursor-pointer", "hover:border-eva-green");
        launchBtn.onclick = () => launchPortfolio(true); // Clic manual
      }

      // Animación progresiva del 0% al 100% en 3.0 segundos (30ms x 100 = 3000ms)
      let lineIndex = 0;
      syncInterval = setInterval(() => {
        if (syncProgress < 100) {
          syncProgress += 1;
          if (syncRateEl) syncRateEl.innerText = syncProgress;
          if (progressBar) progressBar.style.width = syncProgress + "%";

          // Actualizar los 5 bloques de etapa
          const stage = Math.ceil((syncProgress / 100) * 5);
          syncBlocks.forEach(b => {
            const s = parseInt(b.getAttribute("data-stage"), 10);
            if (s <= stage) {
              b.classList.remove("bg-[#1E1038]");
              b.classList.add("bg-eva-acid", "shadow-acid-glow");
            }
          });

          // Imprimir logs escalonados cada 20%
          if (syncProgress % 20 === 0 && lineIndex < telemetryLines.length) {
            if (logContainer) {
              const p = document.createElement("p");
              p.className = "text-[11px] font-mono text-eva-green/90 leading-tight";
              p.innerText = telemetryLines[lineIndex];
              logContainer.appendChild(p);
              logContainer.scrollTop = logContainer.scrollHeight;
            }
            lineIndex++;
          }
        } else {
          clearInterval(syncInterval);
          if (launchBtn) {
            launchBtn.innerText = "⚡ SISTEMA LISTO // ENTRAR";
            launchBtn.classList.remove("text-eva-muted");
            launchBtn.classList.add("bg-eva-green", "text-black", "shadow-[0_0_20px_#4DFF36]");
          }
          // Auto-lanzamiento después de 0.8 segundos de llegar al 100%
          autoLaunchTimeout = setTimeout(() => {
            launchPortfolio(false);
          }, 800);
        }
      }, 30);

      // Escuchar teclas rápidas (Enter, Espacio, ESC)
      window.addEventListener("keydown", handleBootKeys);
    }

    function handleBootKeys(e) {
      if (hasLaunched) return;
      if (e.key === "Enter" || e.key === " " || e.code === "Space" || e.key === "Escape") {
        e.preventDefault();
        launchPortfolio(true);
      }
    }

