  function getHorizontalOffset(idx, activeIdx, total) {
    if (total <= 1) return "0";
    let diff = idx - activeIdx;
    const half = Math.floor(total / 2);
    if (diff > half) diff -= total;
    if (diff < -half) diff += total;

    if (total === 2) {
      return diff === 0 ? "0" : "1";
    }
    if (total === 3) {
      if (diff === 0) return "0";
      return diff < 0 ? "-1" : "1";
    }
    if (total === 4) {
      if (diff === 0) return "0";
      if (diff === -1) return "-1";
      if (diff === 1) return "1";
      return "2";
    }
    if (Math.abs(diff) <= 2) {
      return String(diff);
    }
    return "hidden";
  }

