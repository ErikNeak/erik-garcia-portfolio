    function initScrollReveals() {
      const revealElements = document.querySelectorAll('.hud-reveal, .reveal-item');
      const revealEl = (el) => {
        el.classList.remove('opacity-0', 'translate-y-8', 'blur-sm');
        el.classList.add('opacity-100', 'translate-y-0', 'blur-0');
      };

      if ('IntersectionObserver' in window) {
        const observer = new IntersectionObserver((entries, obs) => {
          entries.forEach(entry => {
            if (entry.isIntersecting) {
              revealEl(entry.target);
              obs.unobserve(entry.target);
            }
          });
        }, {
        threshold: 0.05,
          rootMargin: '50px 0px 50px 0px'
        });

        revealElements.forEach(el => {
          const rect = el.getBoundingClientRect();
          if (rect.top < window.innerHeight + 150 && rect.bottom > -150) {
            revealEl(el);
          } else {
            observer.observe(el);
          }
        });
      } else {
        revealElements.forEach(revealEl);
      }
    }

    function initDynamicCounters() {
      const counters = document.querySelectorAll('.counter-val');
      if (!counters.length) return;

      const animateCounter = (el) => {
        const target = parseFloat(el.getAttribute('data-target')) || 0;
        const prefix = el.getAttribute('data-prefix') || '';
        const suffix = el.getAttribute('data-suffix') || '';
        const duration = 1600;
        const startTime = performance.now();

        function update(currentTime) {
          const elapsed = currentTime - startTime;
          const progress = Math.min(elapsed / duration, 1);
          const easeOut = 1 - Math.pow(1 - progress, 3);
          const currentVal = Math.floor(easeOut * target);

          el.textContent = `${prefix}${currentVal}${suffix}`;

          if (progress < 1) {
            requestAnimationFrame(update);
          } else {
            el.textContent = `${prefix}${target}${suffix}`;
          }
        }

        requestAnimationFrame(update);
      };

      if ('IntersectionObserver' in window) {
        const counterObserver = new IntersectionObserver((entries, obs) => {
          entries.forEach(entry => {
            if (entry.isIntersecting) {
              animateCounter(entry.target);
              obs.unobserve(entry.target);
            }
          });
        }, { threshold: 0.25 });

        counters.forEach(c => counterObserver.observe(c));
      } else {
        counters.forEach(c => animateCounter(c));
      }
    }

